    subj = q.get('subject', '')
    ans = q['answer']
    options = q.get('options', [])
    correct_opt = options[ans - 1] if len(options) >= ans and options[ans - 1] else f"{ans}번"
    
    # 1. Match knowledge base patterns
    for pat, exp in EXPLANATION_PATTERNS:
        if re.search(pat, text):
            return f"정답: {ans}번 [{correct_opt}]\n\n[핵심 해설]\n{exp}"
            
